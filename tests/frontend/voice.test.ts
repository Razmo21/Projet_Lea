test('microphone refusal is explicit and a late permission grant releases every track', async () => {
  const original = Object.getOwnPropertyDescriptor(globalThis, 'navigator')
  const oldRecorder = (globalThis as any).MediaRecorder
  ;(globalThis as any).MediaRecorder = class {}
  try {
    Object.defineProperty(globalThis, 'navigator', { configurable: true, value: { mediaDevices: { getUserMedia: async () => { throw new DOMException('No', 'NotAllowedError') } } } })
    await assert.rejects(new MicrophoneCapture().start('', () => {}), /refusée/)
    let grant: (value: any) => void = () => {}
    Object.defineProperty(globalThis, 'navigator', { configurable: true, value: { mediaDevices: { getUserMedia: () => new Promise((resolve) => { grant = resolve }) } } })
    let stopped = 0
    const mic = new MicrophoneCapture(), pending = mic.start('', () => {})
    mic.cancel(); grant({ getTracks: () => [{ stop: () => stopped++ }] })
    await pending
    assert.equal(stopped, 1)
  } finally {
    if (original) Object.defineProperty(globalThis, 'navigator', original)
    ;(globalThis as any).MediaRecorder = oldRecorder
  }
})

test('microphone absence, disconnection and duration cap release the capture without sending', async () => {
  const original = Object.getOwnPropertyDescriptor(globalThis, 'navigator')
  const oldRecorder = (globalThis as any).MediaRecorder
  const originalTimer = globalThis.setTimeout
  const originalClear = globalThis.clearTimeout
  let stop = 0, recorderStop = 0, cap: () => void = () => {}
  const track: any = { onended: null, stop() { stop++ } }
  ;(globalThis as any).MediaRecorder = class {
    static isTypeSupported() { return true }
    state = 'inactive'
    start() { this.state = 'recording' }
    stop() { this.state = 'inactive'; recorderStop++ }
  }
  try {
    Object.defineProperty(globalThis, 'navigator', { configurable: true, value: { mediaDevices: { getUserMedia: async () => { throw new DOMException('Absent', 'NotFoundError') } } } })
    await assert.rejects(new MicrophoneCapture().start('missing', () => {}), /absent/)
    Object.defineProperty(globalThis, 'navigator', { configurable: true, value: { mediaDevices: { getUserMedia: async () => ({ getTracks: () => [track] }) } } })
    ;(globalThis as any).setTimeout = (callback: () => void, ms: number) => { assert.equal(ms, 120000); cap = callback; return 1 }
    ;(globalThis as any).clearTimeout = () => {}
    let failure = ''
    const disconnected = new MicrophoneCapture()
    await disconnected.start('', error => { failure = error.message })
    track.onended()
    assert.match(failure, /déconnecté/); assert.equal(stop, 1); assert.equal(recorderStop, 1)
    const long = new MicrophoneCapture()
    await long.start('', error => { failure = error.message })
    cap()
    assert.match(failure, /120 secondes/); assert.equal(stop, 2); assert.equal(recorderStop, 2)
    long.cancel(); assert.equal(stop, 2)
    await assert.rejects(long.stop(), /Aucun enregistrement/)
  } finally {
    if (original) Object.defineProperty(globalThis, 'navigator', original)
    ;(globalThis as any).MediaRecorder = oldRecorder
    globalThis.setTimeout = originalTimer; globalThis.clearTimeout = originalClear
  }
})

// Controlled event scheduling tests the lifecycle; native encoded audio is tested in Edge.
function captureHarness(t: any, supportsOpus = true, decodeError = false) {
  let now = 0
  t.mock.method(performance, 'now', () => now)
  const reports: any[] = []
  t.mock.method(console, 'info', (...args: unknown[]) => reports.push(args))
  t.mock.method(console, 'warn', (...args: unknown[]) => reports.push(args))
  const originals = ['navigator', 'MediaRecorder', 'AudioContext', 'OfflineAudioContext'].map(key => [key, Object.getOwnPropertyDescriptor(globalThis, key)] as const)
  const track = { onended: null, stopped: false, stop() { this.stopped = true } }
  const stream = { getTracks: () => [track] }
  let recorder: any, decodedBytes: Uint8Array | undefined, closed = false
  const header = supportsOpus ? Uint8Array.of(0x1a, 0x45, 0xdf, 0xa3) : Uint8Array.of(0, 0, 0, 24, 102, 116, 121, 112)
  const mime = supportsOpus ? 'audio/webm;codecs=opus' : 'audio/mp4;codecs=mp4a.40.2'
  const replacements: Record<string, unknown> = {
    navigator: { mediaDevices: { getUserMedia: async () => stream } },
    MediaRecorder: class {
      static isTypeSupported(type: string) { assert.equal(type, 'audio/webm;codecs=opus'); return supportsOpus }
      state = 'inactive'; mimeType = mime; ondataavailable: any; onstop: any
      constructor(_stream: unknown, options: unknown) { assert.deepEqual(options, supportsOpus ? { mimeType: mime } : undefined); recorder = this }
      start() { this.state = 'recording' }
      stop() { this.state = 'inactive' }
    },
    AudioContext: class {
      state = 'running'
      async decodeAudioData(buffer: ArrayBuffer) {
        assert.equal(track.stopped, true)
        decodedBytes = new Uint8Array(buffer)
        if (decodeError) throw new DOMException('Unable to decode audio data', 'EncodingError')
        return { duration: 1, sampleRate: 48000, numberOfChannels: 2 }
      }
      async close() { closed = true; this.state = 'closed' }
    },
    OfflineAudioContext: class {
      destination = {}
      constructor(channels: number, samples: number, rate: number) { assert.deepEqual([channels, samples, rate], [1, 16000, 16000]) }
      createBufferSource() { return { buffer: undefined, connect() {}, start() {} } }
      async startRendering() { return { getChannelData: () => new Float32Array(16000).fill(.1) } }
    },
  }
  for (const [key, value] of Object.entries(replacements)) Object.defineProperty(globalThis, key, { configurable: true, value })
  t.after(() => {
    for (const [key, descriptor] of originals) {
      if (descriptor) Object.defineProperty(globalThis, key, descriptor)
      else Reflect.deleteProperty(globalThis, key)
    }
  })
  return {
    track, reports, header, mime,
    elapsed() { now = 1100 },
    data(bytes: Uint8Array) { recorder.ondataavailable?.({ data: new Blob([bytes], { type: mime }) }) },
    finish() { recorder.onstop?.() },
    inspected: () => ({ decodedBytes, closed }),
  }
}

for (const supportsOpus of [true, false]) test(`capture waits for final data and stop before ${supportsOpus ? 'WebM' : 'MP4'} decoding and WAV conversion (mock decoder)`, async t => {
  const h = captureHarness(t, supportsOpus)
  const mic = new MicrophoneCapture()
  await mic.start('', () => assert.fail('Unexpected capture failure'))
  h.data(h.header); h.elapsed()
  const pending = mic.stop()
  assert.equal(h.track.stopped, false, 'Do not cut the encoder source before its final flush')
  assert.equal(h.inspected().decodedBytes, undefined)
  h.data(Uint8Array.of(1, 2, 3)); h.data(new Uint8Array()); h.finish()
  const wav = await pending
  assert.deepEqual(h.inspected().decodedBytes, Uint8Array.from([...h.header, 1, 2, 3]))
  assert.equal(audioContainer(wav), 'wav'); assert.equal(wav.length, 32044)
  assert.equal(h.inspected().closed, true)
  const report = h.reports[0][1]
  assert.equal(report.finalized, true); assert.equal(report.recorderMime, h.mime)
  assert.equal(report.chunks.length, 2); assert.equal(report.decodedSeconds, 1)
})

test('a decoder failure retains metadata only, closes audio and never produces replacement WAV', async t => {
  const h = captureHarness(t, true, true), mic = new MicrophoneCapture()
  await mic.start('', () => {})
  h.data(h.header); h.elapsed()
  const pending = mic.stop(); h.finish()
  await assert.rejects(pending, /ne peut pas décoder.*avant envoi à Whisper.*VS Code.*Microsoft Edge externe.*4 octets.*1100 ms/)
  assert.equal(h.track.stopped, true); assert.equal(h.inspected().closed, true)
  assert.deepEqual(h.reports[0][1].chunks, [{ mime: h.mime, bytes: 4 }])
  assert.equal(h.reports[0][1].error, 'EncodingError')
  assert.equal(h.reports[0][1].wavBytes, undefined)
})

test('cancellation during finalization releases tracks and ignores late recorder data', async t => {
  const h = captureHarness(t), mic = new MicrophoneCapture()
  await mic.start('', () => {})
  h.data(h.header); h.elapsed()
  const pending = mic.stop(); mic.cancel(); h.data(Uint8Array.of(1, 2)); h.finish()
  await assert.rejects(pending, /annulé/)
  assert.equal(h.track.stopped, true); assert.equal(h.inspected().decodedBytes, undefined)
})

test('a missing stop event is bounded, releases the microphone and refuses partial audio', async t => {
  const h = captureHarness(t), mic = new MicrophoneCapture()
  await mic.start('', () => {})
  let timeout: () => void = () => {}
  t.mock.method(globalThis, 'setTimeout', (callback: () => void, ms: number) => { assert.equal(ms, 3000); timeout = callback; return 1 })
  h.data(h.header); h.elapsed()
  const pending = mic.stop(); timeout()
  await assert.rejects(pending, /Finalisation audio interrompue/)
  assert.equal(h.track.stopped, true); assert.equal(h.inspected().decodedBytes, undefined)
})

test('empty and too-short captures are rejected before native decoding', async t => {
  const h = captureHarness(t)
  for (const empty of [true, false]) {
    const mic = new MicrophoneCapture()
    await mic.start('', () => {})
    if (!empty) h.data(h.header)
    const pending = mic.stop(); h.finish()
    await assert.rejects(pending, empty ? /vide/ : /trop court/)
    assert.equal(h.inspected().decodedBytes, undefined)
  }
})
