test('WAV encoder clamps PCM16, sets canonical mono 16k headers and enforces duration', () => {
  const samples = new Float32Array(16000); samples[0] = 2; samples[1] = -2
  const wav = pcmWav(samples), view = new DataView(wav.buffer)
  assert.equal(wav.length, 32044); assert.equal(view.getUint32(24, true), 16000)
  assert.equal(view.getInt16(44, true), 32767); assert.equal(view.getInt16(46, true), -32768)
  assert.deepEqual(Buffer.from(audioBase64(wav), 'base64'), Buffer.from(wav))
  assert.throws(() => pcmWav(new Float32Array(3000)))
  assert.throws(() => pcmWav(new Float32Array(120 * 16000 + 1)))
})

